
public class AntivirusApp {

// Stores the antivirus application version.
private String version;

// Stores the current application user.
private User<?> user;

// Shared threat database for the application.
private ThreatDB database = new ThreatDB();

// Update service uses the shared threat database.
private UpdateService updateService =
        new UpdateService(2, 3, database);

// Uses the same threat database to check known signatures.
private ScanEngine scanEngine = new ScanEngine(database);
        // Constructor: initializes the User object and application version
    public AntivirusApp(User<?> user, String version) {

        // Check that the User object is not null
        if (user == null) {
            throw new IllegalArgumentException("User cannot be null");
        }

        // Check that the username is not null or blank
        if (user.getUsername() == null || user.getUsername().isBlank()) {
            throw new IllegalArgumentException("User cannot be empty");
        }

        // Check that the version is not null or blank
        if (version == null || version.isBlank()) {
            throw new IllegalArgumentException("Version cannot be empty");
        }

        // Store the User object and trimmed version
        this.user = user;
        this.version = version.trim();
    }

    // Displays a message when the scanner is requested
    // TODO: Connect this method to the actual Scanner class
    public void startScanner() {
        System.out.println("Starting antivirus scanner...");
    }



    /**
     * Scans the prototype test folder and returns a report.
     *
     * @return the report generated by the Scanner
     */
    public Report scan() {

        // Create a scanner for our harmless test folder
        Scanner scanner = new Scanner("prototype-test");

        // Start scanning and return the results
        return scanner.startScan();
    }

/**
 * Checks a demonstration threat signature against the database.
 *
 * @param signature The signature to search for.
 * @return true if the signature exists in the database.
 */
public boolean checkThreatSignature(String signature) {

    // Reject missing or blank signatures.
    if (signature == null || signature.isBlank()) {
        throw new IllegalArgumentException(
            "Threat signature cannot be empty"
        );
    }

    // Use ScanEngine to search the shared threat database.
    return scanEngine.analyze(signature);
}


    /**
     * Moves the harmless prototype test file into quarantine.
     */
    public void quarantine(String filePath) {

        // Create Prince's quarantine manager
        QuarantineMgr manager = new QuarantineMgr();

        // Move the file selected by the user
        java.io.File quarantinedFile = manager.quarantine(filePath);

        // Display the result
        if (quarantinedFile != null) {
            System.out.println("AntivirusApp quarantine successful.");
            System.out.println(
                "Quarantined file: " + quarantinedFile.getPath()
            );
        } else {
            System.out.println("AntivirusApp quarantine failed.");
        }
    }




/**
 * Checks for and installs a local demonstration
 * antivirus database update.
 */
public void update() {

    // Check whether a newer database version is available.
    if (updateService.check()) {

        System.out.println(
            "A newer antivirus database version is available."
        );

        // Use the existing update service to install the update.
        updateService.updateDB();

    } else {

        // No update is necessary because the database is current.
        System.out.println(
            "Antivirus database is already up to date."
        );
    }
}
  // Returns the current antivirus version
    public String getVersion() {
        return version;
    }

    // Returns the current username from the User object
    public String getUser() {
        return user.getUsername();
    }

    // Displays basic information about the antivirus application
    public void displayAppInfo() {
        System.out.println("Mini Antivirus");
        System.out.println("User: " + user.getUsername());
        System.out.println("Version: " + version);
    }

    // Checks whether the current version matches the supplied version
    public boolean isVersion(String versionToCheck) {
        return version.equals(versionToCheck);
    }

    // Checks whether the supplied username matches the current user
    public boolean isUser(String usernameToCheck) {
        return user.getUsername().equals(usernameToCheck);
    }
}
